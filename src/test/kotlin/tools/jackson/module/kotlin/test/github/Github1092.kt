@Execution(ExecutionMode.CONCURRENT)
class GitHub1092Test {

    companion object {
        private lateinit var testJsonMapper: JsonMapper

        @JvmStatic
        @BeforeAll
        fun setup() {
            testJsonMapper = JsonMapper.builder().addModule(kotlinModule()).build()
        }
    }

    private val roomsString = """{
            "rooms": [
                {
                  "typ": "Living",
                  "animals": [
                        {
                            "typ": "Cat"
                        },
                        {
                            "typ": "Cat"
                        },
                        {
                            "typ": "Cat"
                        },
                        {
                            "typ": "Cat"
                        }
                  ]
                },
                {
                  "typ": "Sleeping",
                  "animals": [
                        {
                            "typ": "Dog"
                        },
                        {
                            "typ": "Dog"
                        },
                        {
                            "typ": "Dog"
                        },
                        {
                            "typ": "Dog"
                        }
                  ]
                }
            ]
    }
    """.trimIndent()

    val result = testJsonMapper.readValue<Result>(roomsString)

    @RepeatedTest(1000)
    fun `try serialisation and deserilization`() {
        assertEquals(result, serializeWithDeserilization(result))
    }

    private fun serializeWithDeserilization(result: Result): Result {
        val personalbetriebslageJson = testJsonMapper.writeValueAsString(result)
        return testJsonMapper.readValue<Result>(personalbetriebslageJson)
    }

}

