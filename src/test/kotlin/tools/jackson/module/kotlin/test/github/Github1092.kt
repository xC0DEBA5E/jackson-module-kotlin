interface Room {
    @get:JsonProperty("typ")
    val typ: RoomType
}

data class LivingRoom(
    override val typ: RoomType,
    val animals: List<Cat>
) : Room

data class SleepingRoom(
    override val typ: RoomType,
    val animals: List<Dog>
) : Room

enum class RoomType {
    Living,
    Sleeping
}

